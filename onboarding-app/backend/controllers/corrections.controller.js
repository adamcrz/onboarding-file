// Shared guard for the correction-scoped document endpoints: resolves the
// correction plus its owning client, and enforces the same visibility rule
// the list endpoint uses so an RM can never reach another RM's contract by
// guessing a correction id.
async function resolveCorrectionForUser(correctionId, user) {
  const correction = await DocumentCorrection.findById(correctionId);
  if (!correction) throw Object.assign(new Error('Document correction not found'), { status: 404 });
  const client = await Client.findOne({ clientId: correction.clientId });
  if (!client) throw Object.assign(new Error('Client not found for this correction'), { status: 409 });
  if (needsScoping(user.role)) {
    const allowed = await ownClientIdsFor(user);
    if (!allowed.includes(correction.clientId)) {
      throw Object.assign(new Error('Not authorised for this correction'), { status: 403 });
    }
  }
  return { correction, client };
}

// GET /api/corrections/documents/:id/download — hands back ONLY the pages this
// correction actually concerns, as their own PDF, so the signer works on the
// affected page instead of the whole contract. Whole pages are copied
// verbatim (see extractPdfPages) — nothing is cropped away.
exports.downloadCorrectionPages = async (req, res) => {
  try {
    const { correction, client } = await resolveCorrectionForUser(req.params.id, req.user);
    const doc = client.documents.find((d) => d.docId === correction.docId);
    if (!doc || !doc.filePath) return res.status(404).json({ error: 'No uploaded file for this document yet' });
    // Uploaded from another machine? Fetch it from the shared store first.
    await fileStore.ensureLocalQuiet(doc.filePath);
    if (!fs.existsSync(doc.filePath)) return res.status(404).json({ error: 'File is missing on disk' });

    // An issue with no page range (an unreadable scan, a non-PDF upload, a
    // contract whose type could not be identified) concerns the document as a
    // whole. Hand back the whole file so it can still be fixed and returned —
    // the fix is the same download → correct → upload loop, just at document
    // scope instead of page scope.
    if (!correction.pageFrom) {
      correction.history.push({
        action: 'downloaded',
        actor: req.user.role === 'rm' ? 'RM' : req.user.role === 'client' ? 'Client' : 'Compliance',
        detail: 'Whole document',
      });
      await correction.save();
      res.setHeader('Content-Type', 'application/octet-stream');
      res.setHeader('Content-Disposition',
        `attachment; filename="${correction.clientId}_${path.basename(doc.filePath)}"`);
      return res.send(fs.readFileSync(doc.filePath));
    }

    const { buffer, from, to } = await extractPdfPages(doc.filePath, correction.pageFrom, correction.pageTo);
    correction.history.push({
      action: 'downloaded',
      actor: req.user.role === 'rm' ? 'RM' : req.user.role === 'client' ? 'Client' : 'Compliance',
      detail: from === to ? `Page ${from}` : `Pages ${from}–${to}`,
    });
    await correction.save();

    const label = from === to ? `page-${from}` : `pages-${from}-${to}`;
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${correction.clientId}_${label}_correction.pdf"`);
    res.send(buffer);
  } catch (err) {
    res.status(err.status || 500).json({ error: err.message });
  }
};

// POST /api/corrections/documents/:id/upload — the corrected page(s) come
// back in. The uploaded file is merged into the ORIGINAL contract at the exact
// position it was taken from (never appended), the affected requirement is
// re-validated on the merged result, and the correction only closes if that
// re-validation actually passes. The previous file is pushed onto the
// document's version history first, so the original upload and every
// corrected generation are both preserved.
exports.uploadCorrectedPages = async (req, res) => {
  let tempPath = null;
  try {
    const { correction, client } = await resolveCorrectionForUser(req.params.id, req.user);
    if (!req.file) return res.status(400).json({ error: 'file is required' });
    tempPath = req.file.path;

    const allowed = ['application/pdf', 'image/jpeg', 'image/png'];
    if (!allowed.includes(req.file.mimetype)) {
      return res.status(415).json({ error: 'Unsupported file type — upload the corrected page as a PDF, JPG or PNG.' });
    }
    if (correction.status === 'corrected') {
      return res.status(409).json({ error: 'This correction has already been resolved.' });
    }

    const doc = client.documents.find((d) => d.docId === correction.docId);
    if (!doc || !doc.filePath) return res.status(409).json({ error: 'This document has no existing file to merge a correction into' });
    await fileStore.ensureLocalQuiet(doc.filePath);
    if (!fs.existsSync(doc.filePath)) return res.status(409).json({ error: 'The original file is missing on disk' });

    const actor = req.user.role === 'rm' ? 'RM' : req.user.role === 'client' ? 'Client' : 'Compliance';

    // Document-scope issue (no page range): the corrected file replaces the
    // whole document rather than being spliced into it. The outgoing file is
    // still preserved as a version, and because there is no page-level rule to
    // re-run, the item goes to Compliance for a human decision instead of
    // closing itself.
    if (!correction.pageFrom) {
      const replacedPath = path.join(path.dirname(doc.filePath),
        `${Date.now()}-corrected${path.extname(req.file.originalname || '') || path.extname(doc.filePath) || '.pdf'}`);
      fs.copyFileSync(req.file.path, replacedPath);
      doc.versions.push({ filePath: doc.filePath, uploadedBy: doc.uploadedBy, date: doc.date, size: doc.size, status: doc.status });
      doc.filePath = replacedPath;
      await fileStore.putFile(replacedPath, null,
        { clientId: client.clientId, clientName: client.name, docName: doc.name });
      doc.uploadedBy = actor;
      doc.date = new Date().toISOString().slice(0, 10);
      doc.size = (fs.statSync(replacedPath).size / 1024 / 1024).toFixed(1) + ' MB';
      doc.status = 'pending';
      doc.missingNote = undefined;

      correction.status = 'resubmitted';
      correction.history.push({
        action: 'corrected-upload',
        actor,
        detail: 'Whole document replaced',
        validation: null,
      });
      client.auditTrail.push({
        action: `Corrected document uploaded for "${doc.name}" — awaiting Compliance review`,
        user: actor,
        time: new Date().toLocaleString(),
        type: 'uploaded',
      });
      await Promise.all([correction.save(), client.save()]);
      return res.json({
        success: true,
        validationPassed: false,
        correction,
        client,
        detail: 'Uploaded — Compliance will review the replacement document.',
      });
    }
    const from = correction.pageFrom;
    const to = correction.pageTo || correction.pageFrom;

    let mergedBuffer;
    try {
      mergedBuffer = await replacePdfPageRange(doc.filePath, from, to, req.file.path, req.file.mimetype);
    } catch (mergeErr) {
      correction.history.push({ action: 'upload-rejected', actor, detail: mergeErr.message, validation: 'failed' });
      await correction.save();
      return res.status(mergeErr.status || 422).json({ error: mergeErr.message });
    }

    // Preserve the outgoing file as a version before the merged one replaces
    // it — the original upload is never overwritten in place.
    const mergedPath = path.join(path.dirname(doc.filePath), `${Date.now()}-corrected-p${from}${path.extname(doc.filePath) || '.pdf'}`);
    fs.writeFileSync(mergedPath, mergedBuffer);
    doc.versions.push({ filePath: doc.filePath, uploadedBy: doc.uploadedBy, date: doc.date, size: doc.size, status: doc.status });
    doc.filePath = mergedPath;
    await fileStore.putFile(mergedPath, null,
      { clientId: client.clientId, clientName: client.name, docName: doc.name });
    doc.uploadedBy = actor;
    doc.date = new Date().toISOString().slice(0, 10);
    doc.size = (mergedBuffer.length / 1024 / 1024).toFixed(1) + ' MB';
    doc.status = 'pending';

    // Re-check ONLY the requirement this correction represents. A broad
    // re-check would re-report every other still-open issue in the document
    // and duplicate their correction rows.
    const templateId = correction.templateId || inferContractTemplateId(doc.name);
    let passed = false;
    let failureDetail = null;
    if (templateId && correction.ruleId) {
      const { supported, findings } = await checkContractRequirementsFile(doc.filePath, templateId, {
        onlyRuleIds: [correction.ruleId],
      });
      const finding = findings[0];
      passed = supported && finding ? finding.ok : false;
      if (!passed) failureDetail = finding?.failureText || 'the uploaded page still does not satisfy this requirement.';
    } else {
      // No rule to re-run against (e.g. a manually created correction) — the
      // merge succeeded, so hand it to Compliance for a human decision rather
      // than silently declaring it fixed.
      failureDetail = 'merged, but this item has no automatic check — Compliance must confirm it manually.';
    }

    if (passed) {
      correction.status = 'corrected';
      doc.missingNote = undefined;
    } else {
      // Still not right: stays visible and actionable rather than closing.
      correction.status = 'pending';
      correction.issue = `${correction.issue.split(':')[0]}: ${failureDetail}`;
      doc.missingNote = failureDetail;
    }
    correction.history.push({
      action: 'corrected-upload',
      actor,
      detail: from === to ? `Page ${from} replaced` : `Pages ${from}–${to} replaced`,
      validation: passed ? 'passed' : 'failed',
    });

    client.auditTrail.push({
      action: `Correction upload for "${doc.name}" (${from === to ? `page ${from}` : `pages ${from}–${to}`}) — validation ${passed ? 'passed' : 'failed'}`,
      user: actor,
      time: new Date().toLocaleString(),
      type: passed ? 'approved' : 'requested',
    });

    await Promise.all([correction.save(), client.save()]);
    res.json({ success: true, validationPassed: passed, correction, client, detail: failureDetail });
  } catch (err) {
    res.status(err.status || 500).json({ error: err.message });
  } finally {
    if (tempPath) fs.unlink(tempPath, () => {});
  }
};

// Called automatically by upload-time validation (missing signature stamp,
// failed checkbox/initials check) as well as manual flags.
exports.createDocumentCorrection = async (req, res) => {
  const { clientId, docId, docName, issue, page } = req.body;
  if (!clientId || !docName || !issue) {
    return res.status(400).json({ error: 'clientId, docName and issue are required' });
  }
  try {
    const item = await DocumentCorrection.create({ clientId, docId, docName, issue, page, status: 'pending' });
    res.json(item);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

exports.updateDocumentCorrectionStatus = async (req, res) => {
  const { status } = req.body;
  if (!['resubmitted', 'corrected'].includes(status)) {
    return res.status(400).json({ error: 'status must be "resubmitted" or "corrected"' });
  }
  try {
    const item = await DocumentCorrection.findById(req.params.id);
    if (!item) return res.status(404).json({ error: 'Document correction not found' });
    if (req.user.role === 'rm') {
      const owningClient = await Client.findOne({ clientId: item.clientId });
      if (!owningClient || owningClient.rm !== req.user.rmCode) {
        return res.status(403).json({ error: 'Not authorised for this correction' });
      }
    }

    item.status = status;
    await item.save();

    const client = await Client.findOne({ clientId: item.clientId });
    if (client) {
      client.auditTrail.push({
        action: `Document correction "${item.docName}" marked ${status}`,
        user: status === 'corrected' ? 'Compliance' : 'RM',
        time: new Date().toLocaleString(),
        type: status === 'corrected' ? 'approved' : 'submitted',
      });
      await client.save();
    }

    await notifyRm(`Document correction "${item.docName}" marked ${status}${client ? ` (${client.name})` : ''}`,
      status === 'corrected' ? 'success' : 'info',
      { rmCode: client?.rm, clientId: item.clientId, page: 'contract-prep' });

    res.json(item);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};
