// Corrections only carry a `clientId` string, not an RM/user link, so
// visibility for a scoped role is derived by first resolving which clients
// are theirs: an RM's own book, or a client's own single case.
const ownClientIdsFor = async (user) => {
  if (user.role === 'client') {
    const own = await Client.findOne({ userId: user.id }).select('clientId');
    return own ? [own.clientId] : [];
  }
  const clients = await Client.find({ rm: user.rmCode || '__none__' }).select('clientId');
  return clients.map(c => c.clientId);
};
const needsScoping = (role) => role === 'rm' || role === 'client';

exports.listKycCorrections = async (req, res) => {
  try {
    const filter = {};
    if (needsScoping(req.user.role)) filter.clientId = { $in: await ownClientIdsFor(req.user) };
    const items = await KycCorrection.find(filter).sort({ createdAt: -1 });

    // Drop rows for fields the canonical KYC schema no longer contains. The
    // questionnaire never renders them, so they can never be answered — left
    // visible they would show as permanently outstanding and keep a submitted
    // questionnaire sitting in "To Complete". Retiring them for good happens on
    // the next write (syncKycCorrectionsForClient); reads simply do not show
    // them, because a GET must not reclassify records.
    const types = new Map(
      (await Client.find({ clientId: { $in: [...new Set(items.map((i) => i.clientId))] } })
        .select('clientId type')).map((c) => [c.clientId, c.type])
    );
    const inCurrentSchema = (item) => {
      if (!item.autoGenerated || !item.fieldKey) return true;
      const type = types.get(item.clientId);
      if (!type) return true;
      return (REQUIRED_KYC_FIELDS[type] || []).some((field) => field.key === item.fieldKey);
    };

    res.json(items.filter(inCurrentSchema));
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

// Compliance-only: confirm a resubmitted field as correct, or reject it (or
// any already-resolved field) back into 'needs_correction'. RMs/clients never
// flip a correction's status directly — they only ever provide the actual
// field value, via resubmitKycSection below, which drives the status itself.
exports.updateKycCorrectionStatus = async (req, res) => {
  const { status, reason } = req.body;
  if (!['needs_correction', 'corrected'].includes(status)) {
    return res.status(400).json({ error: 'status must be "needs_correction" or "corrected"' });
  }
  if (!isComplianceRole(req.user.role)) {
    return res.status(403).json({ error: 'Only Compliance can confirm or reject a KYC correction' });
  }
  try {
    const item = status === 'corrected'
      ? await approveKycCorrection(req.params.id)
      : await rejectKycCorrection(req.params.id, reason);

    if (status === 'corrected') {
      const owner = await Client.findOne({ clientId: item.clientId }).select('_id');
      if (owner) await refreshVerificationFlag(owner._id);
    } else {
      const owner = await Client.findOne({ clientId: item.clientId }).select('_id');
      if (owner) {
        await setKycTaskStatus(owner._id, 'pending');
      }
    }

    const owningClient = await Client.findOne({ clientId: item.clientId }).select('rm name');
    await notifyRm(`KYC correction "${item.issue}" marked ${status}${owningClient ? ` (${owningClient.name})` : ''}`,
      status === 'corrected' ? 'success' : 'info',
      { rmCode: owningClient?.rm, clientId: item.clientId, page: 'kyc-tasks' });

    res.json(item);
  } catch (err) {
    res.status(err.status || 500).json({ error: err.message });
  }
};

// RM/Compliance/client fills in every empty (pending or needs_correction)
// field for one page and resubmits it as a unit. The values land in the same
// shared client.kyc record; whether that closes the correction outright or
// hands it to Compliance for verification depends on who's submitting.
exports.resubmitKycSection = async (req, res) => {
  const { clientId, values } = req.body;
  if (!clientId || !values || typeof values !== 'object' || !Object.keys(values).length) {
    return res.status(400).json({ error: 'clientId and at least one field value are required' });
  }
  try {
    const client = await Client.findOne({ clientId });
    if (!client) return res.status(404).json({ error: 'Client not found' });
    if (req.user.role === 'rm' && client.rm !== req.user.rmCode) {
      return res.status(403).json({ error: 'Not authorised for this client' });
    }
    if (req.user.role === 'client' && String(client.userId) !== req.user.id) {
      return res.status(403).json({ error: 'Not authorised for this client' });
    }
    if (!client.kycSubmittedBy) {
      return res.status(409).json({
        error: 'Initial KYC submission must use the full KYC task after every field has been saved',
      });
    }

    const resolvedClientType = client.type;
    const allFields = REQUIRED_KYC_FIELDS[resolvedClientType] || [];
    if (!allFields.length) {
      return res.status(409).json({ error: 'No KYC schema is configured for this legal form' });
    }
    const { values: filteredValues, errors } = validateKycSubmission(
      values,
      resolvedClientType,
      { includeEmpty: true }
    );
    if (errors.length) {
      return res.status(400).json({ error: 'Invalid KYC field values', details: errors });
    }
    if (!Object.keys(filteredValues).length) {
      return res.status(400).json({ error: 'At least one valid KYC field value is required' });
    }
    const blankFields = Object.entries(filteredValues)
      .filter(([, value]) => !value)
      .map(([key]) => key);
    if (blankFields.length) {
      return res.status(409).json({
        error: 'Every correction field must be non-empty before resubmitting',
        details: { missingFields: blankFields },
      });
    }

    const submittedKeys = Object.keys(filteredValues);
    const actionableCorrections = await KycCorrection.find({
      clientId: client.clientId,
      autoGenerated: true,
      fieldKey: { $in: submittedKeys },
      status: 'saved',
    }).select('fieldKey');
    const actionableKeys = new Set(actionableCorrections.map((item) => item.fieldKey));
    const nonCorrectionFields = submittedKeys.filter((key) => !actionableKeys.has(key));
    if (nonCorrectionFields.length) {
      return res.status(409).json({
        error: 'Only saved KYC correction fields can be resubmitted through this endpoint',
        details: { fields: nonCorrectionFields },
      });
    }
    const unsavedFields = submittedKeys.filter(
      (key) => filteredValues[key] !== String(client.kyc?.[key] ?? '').trim()
    );
    if (unsavedFields.length) {
      return res.status(409).json({
        error: 'KYC corrections contain unsaved changes; save the latest values before resubmitting',
        details: { unsavedFields },
      });
    }
    const missingFields = missingKycFieldDefinitions(client.kyc, resolvedClientType)
      .map((field) => field.key);
    if (missingFields.length) {
      return res.status(409).json({
        error: 'Save a non-empty value for every KYC field before resubmitting',
        details: { missingFields },
      });
    }

    const submittedBy = req.user.role === 'rm' ? 'rm' : isComplianceRole(req.user.role) ? 'compliance' : 'client';
    const submittedAt = new Date();
    // Compliance is the reviewer, so a Compliance-authored resubmission has
    // no one left to review it — it self-verifies straight to approved,
    // matching the same shortcut on the main KYC Tasks submit path.
    // Submitting is never approving, whoever does it. A completed
    // questionnaire always goes to Compliance review; only the explicit
    // verify/approve action records sign-off.
    const selfVerifies = false;
    const approvedBy = selfVerifies ? String(req.user.email || req.user.name || req.user.id || 'Compliance') : undefined;
    const auditEntry = selfVerifies
      ? {
          action: `KYC section resubmitted and approved by Compliance (${Object.keys(filteredValues).length} field${Object.keys(filteredValues).length === 1 ? '' : 's'})`,
          user: 'Compliance',
          time: new Date().toLocaleString(),
          type: 'approved',
        }
      : {
          action: `KYC section resubmitted (${Object.keys(filteredValues).length} field${Object.keys(filteredValues).length === 1 ? '' : 's'})`,
          user: submittedBy === 'rm' ? (client.rm || 'RM') : client.name,
          time: new Date().toLocaleString(),
          type: 'submitted',
        };
    const sectionUpdate = {
      $set: {
        kycSubmittedBy: submittedBy,
        kycSubmittedAt: submittedAt,
        ...(selfVerifies
          ? { kycAwaitingVerification: false, kycStatus: 'approved', kycApprovedAt: submittedAt, kycApprovedBy: approvedBy }
          : { kycAwaitingVerification: true, kycStatus: 'under_review' }),
      },
      $push: { auditTrail: auditEntry },
    };
    if (!selfVerifies) sectionUpdate.$unset = { kycApprovedAt: 1, kycApprovedBy: 1 };
    const updatedClient = await Client.findOneAndUpdate(
      {
        _id: client._id,
        type: resolvedClientType,
        ...Object.fromEntries(
          allFields.map(({ key }) => [`kyc.${key}`, client.kyc[key]])
        ),
      },
      sectionUpdate,
      { new: true, runValidators: true }
    );
    if (!updatedClient) {
      return res.status(409).json({ error: 'Client legal form changed while the KYC section was being submitted' });
    }
    // First submission (or any later one) is what makes "still missing"
    // meaningful — detect gaps now, across every field, not just the ones
    // just submitted, then move whichever of those had an open correction.
    await submitKycFields(updatedClient._id, Object.keys(filteredValues), submittedBy);
    await syncKycCorrectionsForClient(updatedClient._id);
    await setKycTaskStatus(updatedClient._id, selfVerifies ? 'approved' : 'under_review', submittedAt);

    res.json(updatedClient);
  } catch (err) {
    res.status(err.status || 500).json({ error: err.message });
  }
};

// Draft save for one page's worth of fields — persists whatever's filled in
// without submitting it to Compliance. Unlike resubmitKycSection, a partial
// set of values is fine, and kycSubmittedBy/kycAwaitingVerification are left
// untouched: a Save must never look, to Compliance, like a real submission.
exports.saveKycSection = async (req, res) => {
  const { clientId, values } = req.body;
  if (!clientId || !values || typeof values !== 'object' || !Object.keys(values).length) {
    return res.status(400).json({ error: 'clientId and at least one field value are required' });
  }
  try {
    const client = await Client.findOne({ clientId });
    if (!client) return res.status(404).json({ error: 'Client not found' });
    if (req.user.role === 'rm' && client.rm !== req.user.rmCode) {
      return res.status(403).json({ error: 'Not authorised for this client' });
    }
    if (req.user.role === 'client' && String(client.userId) !== req.user.id) {
      return res.status(403).json({ error: 'Not authorised for this client' });
    }

    const resolvedClientType = client.type;
    const { values: filteredValues, errors } = validateKycSubmission(
      values,
      resolvedClientType,
      { includeEmpty: true }
    );
    if (errors.length) {
      return res.status(400).json({ error: 'Invalid KYC field values', details: errors });
    }
    if (!Object.keys(filteredValues).length) {
      return res.status(400).json({ error: 'At least one configured KYC field is required' });
    }

    const savedBy = req.user.role === 'rm' ? 'rm' : isComplianceRole(req.user.role) ? 'compliance' : 'client';
    const changed = Object.entries(filteredValues).some(
      ([key, value]) => value !== String(client.kyc?.[key] ?? '').trim()
    );
    const kycFieldUpdates = Object.fromEntries(
      Object.entries(filteredValues).map(([key, value]) => [`kyc.${key}`, value])
    );
    if (changed) {
      kycFieldUpdates.kycStatus = 'draft';
      kycFieldUpdates.kycAwaitingVerification = false;
    }
    const updatedClient = await Client.findOneAndUpdate(
      { _id: client._id, type: resolvedClientType },
      {
        $set: kycFieldUpdates,
        ...(changed ? {
          $unset: {
            kycSubmittedAt: 1,
            kycApprovedAt: 1,
            kycApprovedBy: 1,
          },
        } : {}),
      },
      { new: true, runValidators: true }
    );
    if (!updatedClient) {
      return res.status(409).json({ error: 'Client legal form changed while the KYC section was being saved' });
    }

    await saveKycFields(updatedClient._id, Object.keys(filteredValues), savedBy);
    await markBlankKycFields(
      updatedClient._id,
      Object.keys(filteredValues).filter((key) => !filteredValues[key]),
      savedBy
    );
    await syncKycCorrectionsForClient(updatedClient._id);
    if (changed) await setKycTaskStatus(updatedClient._id, 'pending');

    res.json(updatedClient);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

// Compliance-only: flag an already-filled (and possibly already-corrected)
// field as wrong even though nothing detected it as missing — clears the
// value and reopens it as 'needs_correction' rather than a first-time gap.
exports.flagKycField = async (req, res) => {
  const { clientId, fieldKey } = req.body;
  if (!clientId || !fieldKey) {
    return res.status(400).json({ error: 'clientId and fieldKey are required' });
  }
  if (!isComplianceRole(req.user.role)) {
    return res.status(403).json({ error: 'Only Compliance can flag a KYC field as incorrect' });
  }
  try {
    const client = await Client.findOne({ clientId });
    if (!client) return res.status(404).json({ error: 'Client not found' });
    // The service owns this rule (it also has to allow the 2nd..nth flag of a
    // single review, where the first flag already sent the KYC back to draft).
    // Duplicating a stricter check here would reject those before it ran.

    const correction = await flagFieldIncorrect(client._id, fieldKey);
    await setKycTaskStatus(client._id, 'pending');

    res.json(correction);
  } catch (err) {
    res.status(err.status || 500).json({ error: err.message });
  }
};

// Compliance-only: the opposite of flagKycField — explicitly sign off on a
// currently-filled field even though nothing ever flagged it, so every field
// carries the same "who confirmed it, when" trail, not just the ones that
// happened to go through a correction cycle.
exports.confirmKycField = async (req, res) => {
  const { clientId, fieldKey } = req.body;
  if (!clientId || !fieldKey) {
    return res.status(400).json({ error: 'clientId and fieldKey are required' });
  }
  if (!isComplianceRole(req.user.role)) {
    return res.status(403).json({ error: 'Only Compliance can confirm a KYC field as correct' });
  }
  try {
    const client = await Client.findOne({ clientId });
    if (!client) return res.status(404).json({ error: 'Client not found' });
    if (!['under_review', 'approved'].includes(effectiveKycStatus(client))) {
      return res.status(409).json({
        error: 'Only a KYC submitted for review or already approved can be confirmed field-by-field',
      });
    }

    const correction = await confirmFieldCorrect(client._id, fieldKey);
    res.json(correction);
  } catch (err) {
    res.status(err.status || 500).json({ error: err.message });
  }
};

